    [Fact]
    public async Task GeneratesAuditProperties_InGlobalNamespace()
    {
        const string source = """
            #nullable enable
            using Ling.Audit;

            public partial class GlobalEntity : IHasCreator<string>, IHasCreationTime
            {
            }
            """;

        const string generatedCode = """
            // <auto-generated/>

            #pragma warning disable
            #nullable enable annotations

            [global::System.CodeDom.Compiler.GeneratedCode("Ling.Audit.SourceGenerators", "2.0.1")]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            partial class GlobalEntity
            {
                /// <inheritdoc/>
                public virtual global::System.String? CreatedBy { get; set; }

                /// <inheritdoc cref="global::Ling.Audit.IHasCreationTime.CreatedAt"/>
                public virtual global::System.DateTimeOffset CreatedAt { get; set; }
            }

            """;

        await VerifyCS.VerifySourceGeneratorAsync(source, ("GlobalEntity.g.cs", generatedCode));
    }

